// Layer 1 of Bleep Script: patch scripts run in the sandbox and become cells, checked against the module types.   node test/patch.test.mjs
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { runPatchScript, prepare } from "../patch/run.mjs";
import { materialize, normalise, resolveParam } from "../patch/materialize.mjs";

const types = Object.fromEntries(JSON.parse(readFileSync(fileURLToPath(new URL("../../board/ui/demo-types.json", import.meta.url)), "utf8")).map((t) => [t.type, t]));
let failures = 0;
const check = (ok, what, detail = "") => { console.log(`${ok ? "ok  " : "FAIL"} ${what}${detail ? "  " + detail : ""}`); if (!ok) failures++; };
const build = async (source, settings = {}) => {
  const r = await runPatchScript(source, settings);
  if (!r.ok) return { ran: false, problems: r.problems };
  return { ran: true, spec: r.spec, ...materialize(r.spec, types, { cellId: "gen-1", parent: "", x: 100, y: 100, generatedBy: "code-1" }) };
};

// ---- a script becomes a cell ---------------------------------------------------------------------------------------------------------------
const SUPERSAW = `import { cell } from "bleep/patch";

export default cell("SuperSaw", {
  description: "Detuned saws.",
  settings: [{ id: "VOICES", name: "Oscillators", min: 1, max: 200, init: 100 }, { id: "SPREAD", name: "Spread (cents)", min: 0, max: 100, init: 30 }],
}, (c: any, s: any) => {
  c.input("pitch", "Pitch", "pitch");
  c.stereoOut();
  const filter = c.add("filter", { cutoff: 4000, resonance: 0.2 });
  for (let i = 0; i < s.VOICES; i++) {
    const detune = s.VOICES > 1 ? (i / (s.VOICES - 1) - 0.5) * s.SPREAD * 2 : 0;
    const osc = c.add("oscillator", { fine: detune }, { name: "Saw " + (i + 1) });
    c.cable(c.cin, "pitch", osc, "pitch");
    c.cable(osc, "saw", filter, "l", 1 / Math.sqrt(s.VOICES));
  }
  c.stereo(filter, c.cout);
});`;
{
  const r = await build(SUPERSAW);
  check(r.ran && r.ok, "the SuperSaw script runs and checks", r.problems && r.problems.map((p) => `${p.line}: ${p.message}`).join(" | "));
  if (r.ok) {
    check(r.summary.modules === 101 && r.summary.cables === 100 * 2 + 2, "100 oscillators and a filter, wired", JSON.stringify(r.summary));
    check(r.nodes[0].type === "cell" && r.nodes[0].inputs.length === 1 && r.nodes[0].outputs.map((o) => o.id).join() === "l,r", "the cell node has the jacks the script declared");
    check(r.nodes.every((n) => n.generatedBy === "code-1") && r.cables.every((c) => c.generatedBy === "code-1"), "everything is marked as generated by the Code node");
    check(r.nodes.filter((n) => n.parent === "gen-1").length === 103 && r.nodes.some((n) => n.type === "cell-in") && r.nodes.some((n) => n.type === "cell-out"), "modules and boundaries are inside the cell");
    const ids = new Set(r.nodes.map((n) => n.id));
    check(ids.size === r.nodes.length && r.cables.every((c) => ids.has(c.from.node) && ids.has(c.to.node)), "ids are unique and every cable ends at a node");
    const osc = r.nodes.find((n) => n.name === "Saw 1");
    check(Math.abs(osc.params.fine - normalise(types.oscillator.params.find((p) => p.id === "fine"), -30)) < 1e-9, "a knob value in units is normalised", String(osc.params.fine));
    const xs = r.nodes.filter((n) => n.type === "oscillator").map((n) => `${n.x},${n.y}`);
    check(new Set(xs).size === 100, "unplaced modules get their own place on a grid");
  }
  const few = await build(SUPERSAW, { VOICES: 3, SPREAD: 10 });
  check(few.ok && few.summary.modules === 4, "settings change the patch: 3 voices", JSON.stringify(few.summary));
  const clamped = await build(SUPERSAW, { VOICES: 9999 });
  check(clamped.ok && clamped.summary.modules === 201, "a setting is held to its range (200 voices)", JSON.stringify(clamped.summary));
}

// ---- mistakes are reported with their line --------------------------------------------------------------------------------------------------
const wrap = (body) => `import { cell } from "bleep/patch";\nexport default cell("T", (c) => {\n  c.input("in", "In", "audio");\n  c.output("out", "Out", "audio");\n${body}\n});`;
const expectProblem = async (what, body, pattern, line) => {
  const r = await build(wrap(body));
  const found = (r.problems || []).find((p) => pattern.test(p.message));
  check(!!found && (line === undefined || found.line === line), what, found ? `line ${found.line}: ${found.message}` : JSON.stringify(r.problems));
};
await expectProblem("an unknown module type", `  c.add("nosuchmodule");`, /not a module a patch can hold/, 5);
await expectProblem("a port is not a module a patch can hold", `  c.add("audio-out");`, /not a module a patch can hold/, 5);
await expectProblem("an unknown knob", `  c.add("filter", { cutof: 100 });`, /no such knob or setting 'cutof'/, 5);
await expectProblem("a value outside a knob's range", `  c.add("filter", { cutoff: 5 });`, /outside 20 to 20000/, 5);
await expectProblem("a wrong kind of value", `  c.add("filter", { cutoff: "high" });`, /expected a number/, 5);
await expectProblem("a choice by an unknown name", `  c.add("filter", { mode: "bogus" });`, /not one of/, 5);
await expectProblem("an unknown output jack", `  const f = c.add("filter"); c.cable(f, "nope", c.cout, "out");`, /no output 'nope'/, 5);
await expectProblem("an unknown input jack", `  const f = c.add("filter"); c.cable(c.cin, "in", f, "nope");`, /no input or modulatable knob 'nope'/, 5);
await expectProblem("notes into audio", `  const k = c.add("keyboard"); const f = c.add("filter"); c.cable(k, "notes", f, "l");`, /can't feed/, 5);
await expectProblem("a cable to a cell output nobody declared", `  const f = c.add("filter"); c.cable(f, "l", c.cout, "zzz");`, /no input or modulatable knob 'zzz'|declare it with c.output/, 5);
await expectProblem("an amount outside -1 to +1", `  const f = c.add("filter"); c.cable(c.cin, "in", f, "l", 5);`, /outside -1 to \+1/, 5);
await expectProblem("a cable from something that is not a module", `  const f = c.add("filter"); c.cable({ id: "ghost" }, "out", f, "l");`, /not a module of this cell/, 5);
await expectProblem("a wrong signal type for a jack", `  c.input("x", "X", "midi");`, /type must be one of/);

// ---- the sandbox ---------------------------------------------------------------------------------------------------------------------------
{
  const r = await runPatchScript(wrap(`  while (true) {}`), {}, { milliseconds: 300 });
  check(!r.ok && /ran longer than 300 ms/.test(r.problems[0].message) && (r.problems[0].line === 4 || r.problems[0].line === 5), "a loop that never ends is stopped, near its line", JSON.stringify(r.problems));
  const m = await runPatchScript(wrap(`  const a = []; for (;;) a.push(new Array(100000).fill(1));`), {}, { memory: 8 * 1024 * 1024, milliseconds: 5000 });
  check(!m.ok && /too much memory|ran longer/.test(m.problems[0].message), "a script that eats memory is stopped", JSON.stringify(m.problems));
  const e = await runPatchScript(wrap(`  const x = null; x.y = 1;`));
  check(!e.ok && e.problems[0].line === 5, "a runtime error comes with its line", JSON.stringify(e.problems));
  const env = await runPatchScript(wrap(`  c.add("filter", { cutoff: typeof fetch === "undefined" && typeof window === "undefined" && typeof process === "undefined" && typeof localStorage === "undefined" && typeof require === "undefined" && typeof XMLHttpRequest === "undefined" && typeof WebSocket === "undefined" && typeof importScripts === "undefined" ? 1000 : 2000 });`));
  const m2 = env.ok ? materialize(env.spec, types, { cellId: "g" }) : null;
  check(env.ok && m2.nodes.find((n) => n.type === "filter").params.cutoff === normalise(types.filter.params.find((p) => p.id === "cutoff"), 1000), "the sandbox has no fetch, window, process, storage, require, XMLHttpRequest, WebSocket or importScripts");
  const imp = await runPatchScript(`import fs from "fs";\nexport default null;`);
  check(!imp.ok && /only "bleep\/patch" can be imported/.test(imp.problems[0].message) && imp.problems[0].line === 1, "an import of anything else is refused", JSON.stringify(imp.problems));
  const none = await runPatchScript(`const x = 1;`);
  check(!none.ok && /export default/.test(none.problems[0].message), "a script without export default is refused");
  const bad = await runPatchScript(`export default 42;`);
  check(!bad.ok && /made with cell/.test(bad.problems[0].message), "an export default that is not a cell is refused", JSON.stringify(bad.problems));
  const syntax = await runPatchScript(`import { cell } from "bleep/patch";\nexport default cell("x", (c) => { c.add( });`);
  check(!syntax.ok && syntax.problems[0].line === 2, "a syntax error comes with its line", JSON.stringify(syntax.problems));
  const huge = await runPatchScript(wrap(`  for (let i = 0; i < 1500; i++) c.add("filter");`));
  check(!huge.ok && /at most 1000 modules/.test(huge.problems[0].message), "too many modules are refused", JSON.stringify(huge.problems));
  const ts = await runPatchScript(`import { cell } from "bleep/patch";\ninterface Opts { n: number }\nconst opts: Opts = { n: 2 };\nexport default cell("T", (c: any) => { for (let i = 0; i < opts.n; i++) c.add("filter"); });`);
  check(ts.ok && ts.spec.nodes.length === 2, "TypeScript syntax (types, interfaces) is understood");
}

// ---- the unit conversions are the engine's ---------------------------------------------------------------------------------------------
{
  const exp = { min: 20, max: 20000, map: "exp", kind: "float" };
  check(Math.abs(normalise(exp, 632.4555) - 0.5) < 1e-4 && resolveParam("t", { ...exp }, 20) === 0 && resolveParam("t", { ...exp }, 20000) === 1, "an exponential knob maps the way the engine does");
}

console.log(failures ? `\n${failures} check(s) failed` : "\nall checks passed");
process.exit(failures ? 1 : 0);
