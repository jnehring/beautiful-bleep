// Child modules: a script uses a module of the library (a standalone .wasm in the module ABI) as an object, and the compiler links the two
// into one file that imports nothing.
//
//   import { Delay } from "./bleep/module-delay";      // a source file this module generates from the child's node type description
//
// The generated class (childSource) declares the child's ABI functions as imports of the module "bleep-module:<id>", and two copy
// functions as imports of "bleep-glue:<id>". After asc, linkChildren merges the script's file with the child's .wasm and a glue file
// (glueWasm) with wasm-merge, which resolves those imports to the child's exports. The result has the script's memory as `memory` and the
// child's own memory, which only the glue touches: a script cannot address a second memory, so the glue copies rows between the two.

import binaryen from "binaryen";
import { mergeWasm } from "./wasm-merge.mjs";

export const CHILD_PREFIX = "bleep-module:";
export const GLUE_PREFIX = "bleep-glue:";
const PARENT = "parent";

/// The imports a module file may keep (module-abi.md section 2): what is left over after linking, the child's own, must be in this list.
const ALLOWED_IMPORTS = new Set([
  "env.emscripten_notify_memory_growth", "env.bleep_media_info", "env.bleep_media_read",
  ...["fd_close", "fd_read", "fd_seek", "fd_write", "environ_get", "environ_sizes_get", "clock_time_get"].map((n) => `wasi_snapshot_preview1.${n}`),
]);

const pascal = (s) => s.replace(/(^|[^A-Za-z0-9]+)([A-Za-z0-9])/g, (_, __, c) => c.toUpperCase()).replace(/[^A-Za-z0-9]/g, "");
const upper = (s) => s.replace(/[^A-Za-z0-9]+/g, "_").replace(/^(\d)/, "_$1").toUpperCase();

/// The name of the class and the file for a child: `id` is the library id ("delay"), `spec` its node type description.
export function childNames(id, spec) {
  const fromName = spec && spec.name ? pascal(String(spec.name)) : "";
  return { className: /^[A-Za-z]/.test(fromName) ? fromName : pascal(id) || "Child", file: `src/bleep/module-${id}.ts` };
}

/// The AssemblyScript source of the class that stands for the child module `id`. `spec`: its node type description (one node type: params,
/// inputs, outputs as the library lists them); `typeIndex`: which node type of the file that is.
export function childSource(id, spec, typeIndex = 0) {
  const { className } = childNames(id, spec);
  const P = spec.params || [], I = spec.inputs || [], O = spec.outputs || [];
  const mod = JSON.stringify(CHILD_PREFIX + id), glue = JSON.stringify(GLUE_PREFIX + id);
  const ext = (m, name, params, ret) => `@external(${m}, "${name}") declare function ${m === mod ? "c" : "g"}_${name}(${params}): ${ret};`;
  const consts = (prefix, list) => list.map((j, i) => `  static readonly ${prefix}_${upper(j.id)}: i32 = ${i};`).join("\n");
  const defaults = P.map((p, i) => `    this.set(${i}, ${Number.isFinite(p.default) ? p.default : 0.5});`).join("\n");
  return `// Generated by the Bleep Script compiler (compiler/child.mjs) from the library module "${id}". Do not edit.
// ${className}: the module "${id}" as an object. It works on whole chunks, not single samples: feed() copies a row of the script's
// buffers into one of its input jacks, process() runs it for n samples, fetch() copies one of its output rows back. A parameter is
// set with set(), a normalised value from 0 to 1, the same value as the knob.
import { CHUNK } from "./abi";

${ext(mod, "_initialize", "", "void")}
${ext(mod, "bleep_create", "typeIndex: i32, sampleRate: f64", "usize")}
${ext(mod, "bleep_inputs_ptr", "h: usize", "usize")}
${ext(mod, "bleep_outputs_ptr", "h: usize", "usize")}
${ext(mod, "bleep_params_ptr", "h: usize", "usize")}
${ext(mod, "bleep_in_connected_ptr", "h: usize", "usize")}
${ext(mod, "bleep_out_connected_ptr", "h: usize", "usize")}
${ext(mod, "bleep_set_knob", "h: usize, index: i32, normalised: f32", "void")}
${ext(mod, "bleep_reset", "h: usize", "void")}
${ext(mod, "bleep_process", "h: usize, numSamples: i32", "i32")}
@external(${glue}, "to_child") declare function g_to_child(dst: usize, src: usize, bytes: i32): void;
@external(${glue}, "from_child") declare function g_from_child(dst: usize, src: usize, bytes: i32): void;

c__initialize();   // the child's own constructors, once, when the script's file starts

const ROW: i32 = CHUNK * 4;   // the bytes of one row

export class ${className} {
${consts("INPUT", I)}
${consts("OUTPUT", O)}
${consts("PARAM", P)}
  private readonly h: usize;
  private readonly inputsAt: usize;
  private readonly outputsAt: usize;
  private readonly paramsAt: usize;
  private readonly values: StaticArray<f32> = new StaticArray<f32>(${Math.max(P.length, 1)} * CHUNK);   // one row per param, as the child reads them
  private dirty: bool = true;

  constructor(sampleRate: f64) {
    this.h = c_bleep_create(${typeIndex}, sampleRate);
    this.inputsAt = c_bleep_inputs_ptr(this.h);
    this.outputsAt = c_bleep_outputs_ptr(this.h);
    this.paramsAt = c_bleep_params_ptr(this.h);
    // every jack counts as patched, so the child computes all its outputs
    const on = new StaticArray<u8>(${Math.max(I.length, O.length) + 1});
    for (let i = 0; i < ${Math.max(I.length, O.length) + 1}; i++) on[i] = 1;
    g_to_child(c_bleep_in_connected_ptr(this.h), changetype<usize>(on), ${I.length + 1});
    g_to_child(c_bleep_out_connected_ptr(this.h), changetype<usize>(on), ${O.length + 1});
${defaults}
  }

  /// The parameter \`index\` (PARAM_...), normalised from 0 to 1.
  set(index: i32, normalised: f32): void {
    const at = index * CHUNK;
    for (let i = 0; i < CHUNK; i++) this.values[at + i] = normalised;
    c_bleep_set_knob(this.h, index, normalised);
    this.dirty = true;
  }

  /// Copies row \`row\` of \`src\` (CHUNK floats) into the input jack \`jack\` (INPUT_...).
  feed(jack: i32, src: StaticArray<f32>, row: i32): void {
    g_to_child(this.inputsAt + <usize>(jack * ROW), changetype<usize>(src) + <usize>(row * ROW), ROW);
  }

  /// Runs the child for \`n\` samples (1 to CHUNK) on what feed() has put in.
  process(n: i32): void {
    if (this.dirty) { g_to_child(this.paramsAt, changetype<usize>(this.values), ${Math.max(P.length, 1)} * ROW); this.dirty = false; }
    c_bleep_process(this.h, n);
  }

  /// Copies the output jack \`jack\` (OUTPUT_...) into row \`row\` of \`dst\`.
  fetch(jack: i32, dst: StaticArray<f32>, row: i32): void {
    g_from_child(changetype<usize>(dst) + <usize>(row * ROW), this.outputsAt + <usize>(jack * ROW), ROW);
  }

  reset(): void { c_bleep_reset(this.h); }
}
`;
}

// ---- the glue file: two memories, two copy functions --------------------------------------------------------------------------------
const leb = (n) => { const out = []; do { let b = n & 0x7f; n >>>= 7; if (n) b |= 0x80; out.push(b); } while (n); return out; };
const str = (s) => { const b = new TextEncoder().encode(s); return [...leb(b.length), ...b]; };
const section = (id, body) => [id, ...leb(body.length), ...body];

/// A WebAssembly file that imports the memory `memory` of the modules `parentName` and `childName` and exports
///   to_child(dst, src, bytes)    copies bytes from the parent's memory to the child's,
///   from_child(dst, src, bytes)  the other way (memory.copy with two memories: the engine's Wasmtime and current browsers run it).
export function glueWasm(parentName, childName) {
  const copy = (d, s) => [0x20, 0, 0x20, 1, 0x20, 2, 0xfc, 0x0a, d, s, 0x0b];   // local.get 0,1,2; memory.copy $d $s; end
  const body = (code) => [...leb(code.length + 1), 0, ...code];                  // size, 0 locals
  const bytes = [
    0x00, 0x61, 0x73, 0x6d, 1, 0, 0, 0,
    ...section(1, [1, 0x60, 3, 0x7f, 0x7f, 0x7f, 0]),                                                           // type 0: (i32 i32 i32) -> ()
    ...section(2, [2, ...str(parentName), ...str("memory"), 0x02, 0x00, 0x00, ...str(childName), ...str("memory"), 0x02, 0x00, 0x00]),   // memory 0 = parent, memory 1 = child
    ...section(3, [2, 0, 0]),                                                                                    // two functions of type 0
    ...section(7, [2, ...str("to_child"), 0x00, 0, ...str("from_child"), 0x00, 1]),
    ...section(10, [2, ...body(copy(1, 0)), ...body(copy(0, 1))]),                                               // to_child: dst in memory 1, src in memory 0
  ];
  return new Uint8Array(bytes);
}

/// The children a compiled script imports: the ids behind its "bleep-module:" and "bleep-glue:" imports.
export function usedChildren(wasm) {
  const ids = new Set();
  for (const i of WebAssembly.Module.imports(new WebAssembly.Module(wasm)))
    for (const prefix of [CHILD_PREFIX, GLUE_PREFIX]) if (i.module.startsWith(prefix)) ids.add(i.module.slice(prefix.length));
  return [...ids];
}

/// Removes every export of `wasm` whose name is not in `keep`: after a merge the child's and the glue's exports are still there, renamed,
/// among them a second memory. The module ABI has one memory and the exports it lists; the rest is not for a host to see.
export function keepExports(wasm, keep) {
  const m = binaryen.readBinary(wasm);
  try {
    m.setFeatures(binaryen.Features.All);
    const names = [];
    for (let i = 0; i < m.getNumExports(); i++) names.push(binaryen.getExportInfo(m.getExportByIndex(i)).name);
    for (const name of names) if (!keep.has(name)) m.removeExport(name);
    m.updateMaps();
    if (!m.validate()) throw new Error("the linked module is not valid");
    return m.emitBinary();
  } finally { m.dispose(); }
}

/// Links a compiled script with the children it uses. `children`: { id: { wasm } }; `mergeTool`: see wasm-merge.mjs (or a function that
/// returns it, or a promise of it). Resolves to the linked bytes. Throws an Error with a message for the user when it cannot.
export async function linkChildren(wasm, ids, children, mergeTool) {
  for (const id of ids) if (!children[id]) throw new Error(`the script uses the module "${id}", which was not provided`);
  const tool = typeof mergeTool === "function" && mergeTool.length === 0 ? await mergeTool() : await mergeTool;
  if (!tool) throw new Error("linking a script with other modules needs the wasm-merge tool, which this build does not have");
  const resolved = typeof tool === "function" ? tool : tool.default;
  const inputs = [{ name: PARENT, bytes: wasm }];
  for (const id of ids) {
    inputs.push({ name: CHILD_PREFIX + id, bytes: children[id].wasm });
    inputs.push({ name: GLUE_PREFIX + id, bytes: glueWasm(PARENT, CHILD_PREFIX + id) });
  }
  const merged = await mergeWasm(resolved, inputs);
  const own = new Set(WebAssembly.Module.exports(new WebAssembly.Module(wasm)).map((e) => e.name));
  const linked = keepExports(merged, own);
  const left = WebAssembly.Module.imports(new WebAssembly.Module(linked)).map((i) => `${i.module}.${i.name}`).filter((n) => !ALLOWED_IMPORTS.has(n));
  if (left.length) throw new Error(`the linked module still imports ${left.slice(0, 3).join(", ")}${left.length > 3 ? ` and ${left.length - 3} more` : ""}, which a module may not`);
  return linked;
}
