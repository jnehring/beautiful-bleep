"""Builds the single-file documentation versions and llms.txt.

Docs are written as small Markdown files in website/content/<audience>/.
This script concatenates them per audience (ordered by the `order:` front
matter, then path) into one file each, for coding assistants and offline
reading, and writes an llms.txt index.

    python3 scripts/build-docs.py [--out DIR] [--base-url URL]

Output (default: build/docs):
    quickstart-full.md
    api-reference-full.md
    spec-v0.1-full.md          (one per spec version)
    user-docs-full.md
    v0.1/...                   the same files under a stable, versioned path
    llms.txt
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "website" / "content"
HEADER = ROOT / "bus" / "include" / "bleep_bus.h"
TOKEN_BUDGET = 80_000  # concept §9.3: beyond this, simplify the API or split the audience


def spec_version() -> str:
    text = HEADER.read_text(encoding="utf-8")
    major = re.search(r"#define BB_SPEC_VERSION_MAJOR (\d+)", text).group(1)
    minor = re.search(r"#define BB_SPEC_VERSION_MINOR (\d+)", text).group(1)
    return f"{major}.{minor}"


def parse(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    meta: dict = {}
    if text.startswith("---\n"):
        end = text.index("\n---\n", 4)
        for line in text[4:end].splitlines():
            if ":" in line:
                key, value = line.split(":", 1)
                meta[key.strip()] = value.strip()
        text = text[end + 5:]
    return meta, text.strip() + "\n"


def ordered(files: list[Path]) -> list[Path]:
    def key(p: Path):
        meta, _ = parse(p)
        return (int(meta.get("order", 1000)), str(p))
    return sorted(files, key=key)


def bundle(title: str, files: list[Path], version: str) -> str:
    parts = [
        f"<!-- Generated by scripts/build-docs.py from website/content. Do not edit. -->\n",
        f"<!-- Bleep Bus spec {version} -->\n\n",
    ]
    if title:
        parts.append(f"# {title}\n\n")
    for f in ordered(files):
        _, body = parse(f)
        rel = f.relative_to(CONTENT)
        parts.append(f"<!-- source: {rel} -->\n{body}\n")
    return "".join(parts)


def estimate_tokens(text: str) -> int:
    return len(text) // 4  # rough: ~4 characters per token for English + code


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "build" / "docs"))
    ap.add_argument("--base-url", default="https://patch.brilliantbleep.com/docs")
    args = ap.parse_args()
    out = Path(args.out)
    version = spec_version()

    dev = CONTENT / "developers"
    bundles = {
        "quickstart-full.md": ("", [dev / "quickstart.md"]),
        "api-reference-full.md": ("", sorted((dev / "api-reference").glob("*.md"))),
        "user-docs-full.md": ("Bleep Patch user documentation", sorted((CONTENT / "users").rglob("*.md"))),
    }
    for spec_dir in sorted((CONTENT / "spec").iterdir()):
        if spec_dir.is_dir():
            bundles[f"spec-{spec_dir.name}-full.md"] = ("", sorted(spec_dir.glob("*.md")))

    ok = True
    for name, (title, files) in bundles.items():
        if not files:
            print(f"error: no sources for {name}", file=sys.stderr)
            ok = False
            continue
        text = bundle(title, files, version)
        for target in (out / name, out / f"v{version}" / name):
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        tokens = estimate_tokens(text)
        flag = ""
        if tokens > TOKEN_BUDGET:
            flag = "  <-- over budget: simplify the API or split the audience"
            ok = False
        print(f"{name:28s} {len(files):3d} files  ~{tokens:6d} tokens{flag}")

    base = args.base_url.rstrip("/")
    specs = [n for n in bundles if n.startswith("spec-")]
    llms = [
        "# Bleep Bus / Bleep Patch",
        "",
        "> Bleep Bus is an open (MIT) protocol and C SDK for sending per-sample control signals",
        "> between audio plugins through shared memory. Bleep Patch is a family of modular-style",
        "> plugins for Ableton Live built on it.",
        "",
        f"Current spec version: {version} (experimental).",
        "",
        "## Developers",
        "",
        f"- [Quickstart]({base}/v{version}/quickstart-full.md): minimal sender and receiver, complete on its own",
        f"- [API reference]({base}/v{version}/api-reference-full.md): every function, type and error, with host notes and pitfalls",
    ]
    for s in specs:
        llms.append(f"- [Specification {s[5:-8]}]({base}/v{version}/{s}): shared-memory layout, memory ordering, timing rules")
    llms += [
        "",
        "## Musicians",
        "",
        f"- [User documentation]({base}/v{version}/user-docs-full.md): getting started, module manuals, Live routing guides",
        "",
    ]
    (out / "llms.txt").write_text("\n".join(llms), encoding="utf-8")
    print(f"wrote {out}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
