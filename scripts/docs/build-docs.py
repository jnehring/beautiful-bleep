"""Builds the single-file documentation versions and llms.txt.

Docs are written as small Markdown files in website/content/<audience>/
(musicians/, developers/; the Bleep Bus spec lives in developers/spec/<version>/).
The module manuals live with the modules, in patch/modules/<name>/doc/, and
belong to the musicians' docs.
This script concatenates them per audience (ordered by the `order:` front
matter, then path) into one file each, for coding assistants and offline
reading, and writes an llms.txt index.

    python3 scripts/docs/build-docs.py [--out DIR] [--base-url URL] [--module-assets DIR]

--module-assets copies the files next to each module's doc (images) to
DIR/<module>/, where the website serves them (/modules/<module>/).

Output (default: build/docs):
    quickstart-full.md
    api-reference-full.md
    spec-v0.1-full.md          (one per spec version)
    user-docs-full.md
    v0.1/...                   the same files under a stable, versioned path
    llms.txt
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
CONTENT = ROOT / "website" / "content"
MODULES = ROOT / "patch" / "modules"
HEADER = ROOT / "bus" / "include" / "bleep_bus.h"
CATEGORIES = ["Sources", "Modulation", "Audio", "Effects", "Utility", "Controllers", "Sequencing", "Drums/Ring", "Drums/Punch"]  # the board's Add menu order
TOKEN_BUDGET = 80_000  # concept §9.3: beyond this, simplify the API or split the audience


def spec_version() -> str:
    text = HEADER.read_text(encoding="utf-8")
    major = re.search(r"#define BB_SPEC_VERSION_MAJOR (\d+)", text).group(1)
    minor = re.search(r"#define BB_SPEC_VERSION_MINOR (\d+)", text).group(1)
    return f"{major}.{minor}"


def parse(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    meta: dict = {}
    if text.startswith("---\n"):
        end = text.index("\n---\n", 4)
        for line in text[4:end].splitlines():
            if ":" in line:
                key, value = line.split(":", 1)
                meta[key.strip()] = value.strip()
        text = text[end + 5:]
    return meta, text.strip() + "\n"


def ordered(files: list[Path]) -> list[Path]:
    def key(p: Path):
        meta, _ = parse(p)
        return (int(meta.get("order", 1000)), str(p))
    return sorted(files, key=key)


def bundle(title: str, files: list[Path], version: str) -> str:
    parts = [
        f"<!-- Generated by scripts/docs/build-docs.py from website/content. Do not edit. -->\n",
        f"<!-- Bleep Bus spec {version} -->\n\n",
    ]
    if title:
        parts.append(f"# {title}\n\n")
    for f in ordered(files):
        _, body = parse(f)
        rel = f.relative_to(CONTENT) if f.is_relative_to(CONTENT) else f.relative_to(ROOT)
        parts.append(f"<!-- source: {rel} -->\n{body}\n")
    return "".join(parts)


def module_docs_by_category() -> dict[str, list[Path]]:
    """patch/modules/<name>/doc/*.md grouped by the board's categories (Sources, Audio, ...), in the board's order.

    The category of a node comes from the board's type list (board/ui/demo-types.json), of a
    kit's overview from its module.json. Inside a folder, the doc named by module.json comes first."""
    types_file = ROOT / "patch" / "board" / "ui" / "demo-types.json"
    categories = {t["type"]: t["category"] for t in json.loads(types_file.read_text(encoding="utf-8"))} if types_file.is_file() else {}
    found: dict[str, list[Path]] = {}
    for meta in sorted(MODULES.glob("*/module.json")):
        info = json.loads(meta.read_text(encoding="utf-8"))
        docs = sorted((meta.parent / "doc").glob("*.md"), key=lambda f: (f.stem != meta.parent.name, f.stem))
        for doc in docs:
            found.setdefault(categories.get(doc.stem) or info.get("category") or "Other", []).append(doc)
    order = {c: i for i, c in enumerate(CATEGORIES)}
    return dict(sorted(found.items(), key=lambda kv: (order.get(kv[0], len(order)), kv[0])))


def category_slug(category: str) -> str:
    return re.sub(r"[^a-z]+", "-", category.lower())


def copy_module_assets(out: Path) -> None:
    for doc_dir in sorted(MODULES.glob("*/doc")):
        for f in doc_dir.iterdir():
            if f.is_file() and f.suffix != ".md":
                target = out / doc_dir.parent.name / f.name
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(f, target)


def estimate_tokens(text: str) -> int:
    return len(text) // 4  # rough: ~4 characters per token for English + code


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "build" / "docs"))
    ap.add_argument("--base-url", default="https://patch.brilliantbleep.com/docs")
    ap.add_argument("--module-assets", help="copy the module docs' images here, one folder per module")
    args = ap.parse_args()
    if args.module_assets:
        copy_module_assets(Path(args.module_assets))
    out = Path(args.out)
    version = spec_version()

    dev = CONTENT / "developers"
    bundles = {
        "developer-overview-full.md": ("", [dev / "overview.md"]),
        "quickstart-full.md": ("", [dev / "quickstart.md"]),
        "api-reference-full.md": ("", sorted((dev / "api-reference").glob("*.md"))),
        "user-docs-full.md": ("Beautiful Bleep user documentation", sorted((CONTENT / "musicians").rglob("*.md"))),
    }
    for key, title in (("modules", "modules"), ("plugins", "plugins"), ("app", "the standalone app"), ("web", "Bleep Play and the web"), ("reference", "reference: ABIs, signing and the store")):
        bundles[f"developer-{key}-full.md"] = (f"Beautiful Bleep developer documentation: {title}", sorted((dev / key).glob("*.md")))
    # The module manuals are too many for one file: one per category.
    module_bundles = {f"modules-{category_slug(c)}-full.md": (f"Beautiful Bleep modules: {c.replace('/', ' · ')}", docs)
                      for c, docs in module_docs_by_category().items()}
    bundles.update(module_bundles)
    for spec_dir in sorted((dev / "spec").iterdir()):
        if spec_dir.is_dir():
            bundles[f"spec-{spec_dir.name}-full.md"] = ("", sorted(spec_dir.glob("*.md")))

    ok = True
    for name, (title, files) in bundles.items():
        if not files:
            print(f"error: no sources for {name}", file=sys.stderr)
            ok = False
            continue
        text = bundle(title, files, version)
        for target in (out / name, out / f"v{version}" / name):
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        tokens = estimate_tokens(text)
        flag = ""
        if tokens > TOKEN_BUDGET:
            flag = "  <-- over budget: simplify the API or split the audience"
            ok = False
        print(f"{name:28s} {len(files):3d} files  ~{tokens:6d} tokens{flag}")

    base = args.base_url.rstrip("/")
    specs = [n for n in bundles if n.startswith("spec-")]
    llms = [
        "# Bleep Bus / Beautiful Bleep",
        "",
        "> Bleep Bus is an open (MIT) protocol and C SDK for sending per-sample control signals",
        "> between audio plugins through shared memory. Beautiful Bleep is a family of modular-style",
        "> plugins for Ableton Live built on it.",
        "",
        f"Current spec version: {version} (experimental).",
        "",
        "## Developers",
        "",
        f"- [Quickstart]({base}/v{version}/quickstart-full.md): minimal sender and receiver, complete on its own",
        f"- [API reference]({base}/v{version}/api-reference-full.md): every function, type and error, with host notes and pitfalls",
    ]
    for s in specs:
        llms.append(f"- [Specification {s[5:-8]}]({base}/v{version}/{s}): shared-memory layout, memory ordering, timing rules")
    llms += [
        f"- [Overview]({base}/v{version}/developer-overview-full.md): which guide is for which developer, and how the pieces fit",
        f"- [Module developers]({base}/v{version}/developer-modules-full.md): writing, packaging and publishing a board module",
        f"- [Plugin developers]({base}/v{version}/developer-plugins-full.md): the Bleep plugins in Live",
        f"- [Standalone app]({base}/v{version}/developer-app-full.md): building and extending the Bleep App",
        f"- [Web]({base}/v{version}/developer-web-full.md): Bleep Play, the board in the browser",
        f"- [Reference]({base}/v{version}/developer-reference-full.md): module ABI, signing, the store, the engine ABI",
        "",
        "## Musicians",
        "",
        f"- [User documentation]({base}/v{version}/user-docs-full.md): getting started, the board, Live routing guides",
    ]
    for name, (title, _) in module_bundles.items():
        llms.append(f"- [{title}]({base}/v{version}/{name}): the manuals of these modules")
    llms += [
        "",
    ]
    (out / "llms.txt").write_text("\n".join(llms), encoding="utf-8")
    print(f"wrote {out}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
